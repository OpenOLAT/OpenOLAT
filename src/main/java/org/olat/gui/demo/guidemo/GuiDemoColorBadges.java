	/**
	 * @param state The state
	 * @param style The style
	 * @return The classes of a status label in this state and style
	 */
	public static String stateClass(State state, String style) {
		String cssClass = "o_state_" + state.name();
		return switch (style) {
			case DARK -> "o_labeled " + cssClass + " o_state_dark";
			case TINT -> "o_labeled " + cssClass + " o_state_tint";
			case LIGHT -> "o_labeled " + cssClass + " o_state_light";
			case TEXT -> "o_labeled_light " + cssClass;
			default -> "o_labeled " + cssClass;
		};
	}

	public record State(String name, String hue, String meaning) {

		public String getCssClass() {
			return "o_state_" + name;
		}

		/**
		 * @return One sample per style, with the classes of the theme
		 */
		public List<Sample> getStyles() {
			return STYLES.stream()
					.map(style -> new Sample(stateClass(this, style), name, this, style))
					.toList();
		}
	}

	public record Group(String name, String wrapper, List<Sample> samples) {
		//
	}

	public record Sample(String cssClass, String text, State state, String style) {

		public String getStateName() {
			return state == null ? "not wired" : state.name();
		}

		public String getStyleName() {
			return style == null ? "" : style;
		}
	}
